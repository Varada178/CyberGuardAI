import re
import pdfplumber


class PDFExtractionError(Exception):
    """Raised when required network-flow features cannot be extracted."""
    pass


class PDFFeatureExtractor:

    # ---------------------------------------------------------
    # 1. EXTRACT TEXT
    # ---------------------------------------------------------

    @staticmethod
    def extract_text(pdf_file):

        text_parts = []

        try:
            with pdfplumber.open(pdf_file) as pdf:

                for page in pdf.pages:

                    text = page.extract_text()

                    if text:
                        text_parts.append(text)

        except Exception as exc:

            raise PDFExtractionError(
                f"Unable to read PDF: {str(exc)}"
            )

        if not text_parts:

            raise PDFExtractionError(
                "No readable text was found in the PDF."
            )

        return "\n".join(text_parts)

    # ---------------------------------------------------------
    # 2. EXTRACT FEATURES
    # ---------------------------------------------------------

    @staticmethod
    def extract_features(pdf_file, required_features):

        text = PDFFeatureExtractor.extract_text(pdf_file)

        print("\n================ PDF TEXT ================\n")
        print(text)
        print("\n===========================================\n")

        rows = PDFFeatureExtractor._find_feature_blocks(
            text,
            required_features
        )

        print("\n================ EXTRACTION RESULT ================\n")

        print(f"Total records detected: {len(rows)}")

        for index, row in enumerate(rows, start=1):

            print(
                f"Record {index}: "
                f"{len(row['features'])}/{len(required_features)} features"
            )

        print("\n====================================================\n")

        if not rows:

            raise PDFExtractionError(
                "No valid network-flow records were found in the PDF."
            )

        return rows

    # ---------------------------------------------------------
    # 3. SPLIT PDF INTO RECORDS
    # ---------------------------------------------------------

    @staticmethod
    def _split_into_records(text):

        """
        Split the PDF text into separate network-flow records.

        Every record generated by our PDF format starts with:

        CyberGuardAI — Network Flow Analysis

        Therefore this heading is used as the record boundary.
        """

        # Normalize different dash characters
        normalized_text = (
            text.replace("—", "-")
                .replace("–", "-")
        )

        # This heading identifies the beginning of every record
        pattern = re.compile(
            r"CyberGuardAI\s*-\s*Network\s*Flow\s*Analysis",
            re.IGNORECASE
        )

        matches = list(pattern.finditer(normalized_text))

        if not matches:

            return [normalized_text]

        records = []

        for index, match in enumerate(matches):

            start = match.start()

            if index + 1 < len(matches):

                end = matches[index + 1].start()

            else:

                end = len(normalized_text)

            record_text = normalized_text[start:end].strip()

            if record_text:

                records.append(record_text)

        return records

    # ---------------------------------------------------------
    # 4. FIND FEATURES INSIDE EACH RECORD
    # ---------------------------------------------------------

    @staticmethod
    def _find_feature_blocks(text, required_features):

        records = PDFFeatureExtractor._split_into_records(text)

        print(
            f"\nDetected {len(records)} possible record(s) in PDF."
        )

        rows = []

        for record_index, record_text in enumerate(
            records,
            start=1
        ):

            print(
                f"\nProcessing Record {record_index}..."
            )

            features = PDFFeatureExtractor._extract_record_features(
                record_text,
                required_features
            )

            print(
                f"Record {record_index}: "
                f"{len(features)}/{len(required_features)} features"
            )

            # Only accept a record if ALL required features exist
            if len(features) == len(required_features):

                rows.append(
                    {
                        "features": features
                    }
                )

            else:

                missing = [
                    feature
                    for feature in required_features
                    if feature not in features
                ]

                print(
                    f"Record {record_index} ignored."
                )

                print(
                    "Missing features:"
                )

                for feature in missing:

                    print(
                        f" - {feature}"
                    )

        return rows

    # ---------------------------------------------------------
    # 5. EXTRACT ONE RECORD
    # ---------------------------------------------------------

    @staticmethod
    def _extract_record_features(
        record_text,
        required_features
    ):

        lines = [
            line.strip()
            for line in record_text.splitlines()
            if line.strip()
        ]

        features = {}

        # -----------------------------------------------------
        # Normalize required feature names
        # -----------------------------------------------------

        feature_lookup = {}

        for feature in required_features:

            normalized = (
                feature.strip()
                .lower()
                .replace(" ", " ")
            )

            feature_lookup[normalized] = feature

        # -----------------------------------------------------
        # Process every line
        # -----------------------------------------------------

        for line in lines:

            # Ignore title/header lines
            if (
                "CyberGuardAI" in line
                or "Network Flow Feature Value" in line
                or "Network-flow record" in line
                or "Record format" in line
            ):
                continue

            # -------------------------------------------------
            # FORMAT:
            #
            # Bwd Packet Length Std 24.8
            #
            # OR
            #
            # Bwd Packet Length Std: 24.8
            # -------------------------------------------------

            matched_feature = None
            raw_value = None

            # -------------------------------------------------
            # First try exact feature-name matching
            # -------------------------------------------------

            # Sort longest first so that:
            #
            # Flow IAT Max
            #
            # is checked before:
            #
            # Flow IAT
            #
            sorted_features = sorted(
                required_features,
                key=len,
                reverse=True
            )

            for feature in sorted_features:

                # Escape feature name for regex
                escaped_feature = re.escape(feature)

                # Feature followed by optional ":" or "="
                pattern = re.compile(
                    rf"^\s*{escaped_feature}\s*[:=]?\s*(.+?)\s*$",
                    re.IGNORECASE
                )

                match = pattern.match(line)

                if match:

                    matched_feature = feature
                    raw_value = match.group(1).strip()

                    break

            # -------------------------------------------------
            # If feature was not found, ignore the line
            # -------------------------------------------------

            if matched_feature is None:

                continue

            # -------------------------------------------------
            # Convert value
            # -------------------------------------------------

            value = PDFFeatureExtractor._convert_value(
                raw_value
            )

            features[matched_feature] = value

        return features

    # ---------------------------------------------------------
    # 6. CONVERT VALUE
    # ---------------------------------------------------------

    @staticmethod
    def _convert_value(value):

        value = value.strip()

        # Remove commas
        value = value.replace(",", "")

        # Handle missing values
        if value.lower() in {
            "nan",
            "null",
            "none",
            "missing",
            "",
        }:

            return 0.0

        try:

            number = float(value)

            # Return integer if it is actually an integer
            if number.is_integer():

                return int(number)

            return number

        except ValueError:

            return value